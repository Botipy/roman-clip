const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  get: () => ipcRenderer.invoke('get'),
  set: (patch) => ipcRenderer.invoke('set', patch),
  clip: () => ipcRenderer.invoke('clip'),
  togglePause: () => ipcRenderer.invoke('togglePause'),
  winMin: () => ipcRenderer.send('win:min'),
  winClose: () => ipcRenderer.send('win:close'),
  clipsList: () => ipcRenderer.invoke('clips:list'),
  clipMeta: (p) => ipcRenderer.invoke('clips:meta', p),
  clipDelete: (p) => ipcRenderer.invoke('clips:delete', p),
  clipReveal: (p) => ipcRenderer.invoke('clips:reveal', p),
  clipOpen: (p) => ipcRenderer.invoke('clips:open', p),
  onClipSaved: (cb) => ipcRenderer.on('clip:saved', (_e, f) => cb(f)),
  checkUpdates: () => ipcRenderer.invoke('checkUpdates'),
  installUpdate: () => ipcRenderer.invoke('installUpdate'),
  pickDir: () => ipcRenderer.invoke('pickDir'),
  openDir: () => ipcRenderer.invoke('openDir'),
  audioDevices: () => ipcRenderer.invoke('audioDevices'),
  displays: () => ipcRenderer.invoke('displays'),
  downloadModel: () => ipcRenderer.invoke('downloadModel'),
  onStatus: (cb) => ipcRenderer.on('status', (_e, s) => cb(s)),
  voiceHeard: (text) => ipcRenderer.send('voice:heard', text),
  sysAudio: (buf) => ipcRenderer.send('sysaudio:data', buf),
});
